"""Scan a MAME ROM directory using the in-memory associative array from rom_daemon_threaded.sh.

The daemon uses a bash coproc, so start_rom_db and all checkrom calls must run
in the same shell. This writes a temporary script and executes it so the
coproc stays alive for the entire scan.

Paths come from data/config.json or the command line.

Sets that are not found, renamed, or (when --us-only is given) non-US
are written to the move script.
"""

from __future__ import annotations

import argparse
import logging
import re
import subprocess
import tempfile
from pathlib import Path

try:
    from .config import (
        get_mame_daemon_script,
        get_mame_roms_directory,
        get_mame_xml_database,
    )
except ImportError:
    from rommanager.config import (
        get_mame_daemon_script,
        get_mame_roms_directory,
        get_mame_xml_database,
    )

log = logging.getLogger(__name__)

# Region markers commonly found in MAME descriptions
_NON_US = re.compile(
    r"\b(japan|japanese|jp\b|europe|euro|pal\b|asia|korea|korean|france|french|"
    r"germany|german|italy|italian|spain|spanish|brazil|brazil|australia|aus\b|"
    r"china|chinese|taiwan|hong kong|hk\b)\b",
    re.I,
)
_US = re.compile(r"\b(usa|us\b|ntsc-u|america|american)\b", re.I)


def is_us_region(text: str) -> bool:
    """Return True if the description looks like a US (or untagged) release."""
    if not text:
        return False
    if _NON_US.search(text):
        return False
    # Explicit US marker, or no region marker at all (treat as keep)
    return True


def scan_with_daemon(
    rom_dir: Path,
    xml_path: Path,
    daemon_script: Path,
    mover_script: Path | None = None,
    us_only: bool = False,
) -> None:
    if not daemon_script.is_file():
        raise FileNotFoundError(f"Daemon script not found: {daemon_script}")
    if not xml_path.is_file():
        raise FileNotFoundError(f"XML file not found: {xml_path}")
    if not rom_dir.is_dir():
        raise FileNotFoundError(f"ROM directory not found: {rom_dir}")

    invalid_dir = rom_dir / "invalidroms"
    invalid_dir.mkdir(exist_ok=True)
    mover = mover_script or (rom_dir / "moveroms.sh")

    zips = sorted(p for p in rom_dir.iterdir() if p.is_file() and p.suffix.lower() == ".zip")
    log.info("Scanning %d zip files in %s%s", len(zips), rom_dir, " (US only)" if us_only else "")

    with tempfile.NamedTemporaryFile("w", suffix=".sh", delete=False) as tmp:
        tmp_path = Path(tmp.name)
        tmp.write("#!/usr/bin/env bash\n")
        # Do not use set -u; the daemon references ROM_DB_PID before the coproc sets it
        tmp.write("set -eo pipefail\n")
        tmp.write(f"source '{daemon_script}'\n")
        tmp.write(f"start_rom_db '{xml_path}'\n")
        tmp.write("echo '===DB_READY==='\n")
        for z in zips:
            tmp.write(f"echo '===CHECK==={z.name}==='\n")
            tmp.write(f"checkrom '{z}' || true\n")
        tmp.write("stop_rom_db\n")

    try:
        log.info("Starting database and scanning in a single session...")
        result = subprocess.run(
            ["bash", str(tmp_path)],
            capture_output=True,
            text=True,
        )
    finally:
        tmp_path.unlink(missing_ok=True)

    output = result.stdout or ""
    if result.returncode != 0 and "===DB_READY===" not in output:
        raise RuntimeError(f"Daemon session failed:\n{result.stderr or result.stdout}")

    # Parse output
    results: dict[str, str] = {}
    for section in output.split("===CHECK==="):
        if "===" not in section:
            continue
        name, _, rest = section.partition("===")
        results[name.strip()] = rest.strip()

    with mover.open("w", encoding="utf-8") as script:
        script.write("#!/usr/bin/env bash\n")
        script.write("# Generated by mame_daemon_scan.py\n")
        note = "unrecognized, renamed"
        if us_only:
            note += ", or non-US"
        script.write(f"# Moves {note} sets into {invalid_dir}\n")
        script.write("set -euo pipefail\n\n")

        for z in zips:
            text = results.get(z.name, "")
            lower = text.lower()
            is_clean_match = bool(text) and "[match]" in lower and "[renamed]" not in lower
            keep = is_clean_match
            reason = "NOT FOUND"

            if is_clean_match and us_only and not is_us_region(text):
                keep = False
                reason = "NON-US"
            elif "[renamed]" in lower:
                keep = False
                reason = "RENAMED"
            elif not is_clean_match:
                keep = False
                reason = "NOT FOUND"

            if keep:
                log.info("%s -> %s", z.name, text.splitlines()[0] if text else "OK")
            else:
                log.warning("%s: %s (%s)", reason, z.name, text or "no output")
                dest = invalid_dir / z.name
                script.write(f'mv -n "{z}" "{dest}"\n')

    mover.chmod(0o755)
    log.info("Move script written: %s", mover)
    log.info("Run it to relocate filtered ROMs: bash %s", mover)


def main() -> None:
    parser = argparse.ArgumentParser(description="Scan MAME ROMs via rom_daemon in-memory array")
    parser.add_argument("rom_dir", nargs="?", type=Path, help="Directory of .zip ROM sets (or read from config)")
    parser.add_argument("xml", nargs="?", type=Path, help="Path to MAME XML (or read from config)")
    parser.add_argument("--daemon-script", type=Path, help="Path to rom_daemon_threaded.sh (or read from config)")
    parser.add_argument("--mover", type=Path, help="Output path for moveroms.sh (default: <rom_dir>/moveroms.sh)")
    parser.add_argument("--us-only", action="store_true", help="Also move non-US sets into invalidroms")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")

    rom_dir = args.rom_dir or Path(get_mame_roms_directory() or "")
    xml_path = args.xml or Path(get_mame_xml_database() or "")
    daemon_script = args.daemon_script or Path(get_mame_daemon_script() or "")

    if not str(rom_dir):
        raise SystemExit("No ROM directory given and none set in data/config.json")
    if not str(xml_path):
        raise SystemExit("No XML path given and none set in data/config.json")
    if not str(daemon_script):
        raise SystemExit("No daemon script given and none set in data/config.json")

    scan_with_daemon(rom_dir, xml_path, daemon_script, args.mover, us_only=args.us_only)


if __name__ == "__main__":
    main()
